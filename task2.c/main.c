/**
 * @file task2.c
 * @brief Робота з квадратними матрицями у статичній пам'яті (мова C).
 * @details Варіант 14: Заповнення матриці A випадковими числами із діапазону [-a; a]
 *          (де a — випадкове число з діапазону 5...10). Визначення індексу стовпця
 *          з найменшим значенням суми елементів за допомогою окремої функції[cite: 9, 10].
 * @author Студент КПІ
 */

#include <stdio.h>
#include <stdlib.h>
#include <time.h>

#define MAX_N 20 // Максимально допустимий розмір статичної матриці

/**
 * @brief Функція для генерації та заповнення матриці випадковими числами.
 * @param A Двовимірний масив (матриця), що заповнюється.
 * @param N Поточний розмір матриці (NxN)[cite: 9].
 * @param a Амлітуда генерації (діапазон [-a; a])[cite: 10].
 */
void fillMatrix(int A[MAX_N][MAX_N], int N, int a) {
    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < N; ++j) {
            // Формування випадкового числа в діапазоні від -a до a
            A[i][j] = rand() % (2 * a + 1) - a;
        }
    }
}

/**
 * @brief Функція для виведення квадратної матриці у форматованому вигляді.
 * @param A Матриця для виведення.
 * @param N Розмір матриці.
 */
void printMatrix(int A[MAX_N][MAX_N], int N) {
    printf("\nЗгенерована матриця A (%dx%d):\n", N, N);
    for (int i = 0; i < N; ++i) {
        for (int j = 0; j < N; ++j) {
            printf("%6d", A[i][j]);
        }
        printf("\n");
    }
}

/**
 * @brief Пошук індексу стовпця з мінімальною сумою елементів.
 * @param A Вхідна матриця.
 * @param N Розмір матриці.
 */
void findMinColumnSum(int A[MAX_N][MAX_N], int N) {
    int minColIndex = 0;
    int minSum = 0;

    // Обчислення суми елементів для першого (індекс 0) стовпця як початкового еталона
    for (int i = 0; i < N; ++i) {
        minSum += A[i][0];
    }

    // Послідовне порівняння сум інших стовпців матриці
    for (int j = 1; j < N; ++j) {
        int currentSum = 0;
        for (int i = 0; i < N; ++i) {
            currentSum += A[i][j];
        }

        // Оновлення мінімального значення та індексу, якщо знайдено меншу суму
        if (currentSum < minSum) {
            minSum = currentSum;
            minColIndex = j;
        }
    }

    // Виведення результатів пошуку на екран українською мовою[cite: 9]
    printf("\n--- РЕЗУЛЬТАТИ АНАЛІЗУ СТОВПЦІВ ---\n");
    printf("Індекс стовпця з найменшою сумою елементів (нумерація з 0): %d\n", minColIndex);
    printf("Номер стовпця (природна нумерація з 1): %d\n", minColIndex + 1);
    printf("Значення мінімальної суми елементів цього стовпця: %d\n", minSum);
}

int main() {
    // Встановлення кодування UTF-8 для коректного відображення української мови в консолі
    system("chcp 65001 > nul");

    // Ініціалізація генератора псевдовипадкових чисел
    srand((unsigned int)time(NULL));

    int N;
    // Організація захисту вводу розмірності матриці
    do {
        printf("Введіть розмірність квадратної матриці N (від 1 до %d): ", MAX_N);
        scanf("%d", &N);
        if (N < 1 || N > MAX_N) {
            printf("Помилка! Некоректний розмір. Повторіть введення.\n");
        }
    } while (N < 1 || N > MAX_N);

    // Генерація випадкового числа 'a' у заданому діапазоні [5; 10][cite: 10]
    int a = rand() % 6 + 5;
    printf("Параметр 'a' (межі діапазону елементів): %d (діапазон: [%d; %d])\n", a, -a, a);

    int A[MAX_N][MAX_N]; // Оголошення статичного двовимірного масиву[cite: 9]

    // Виклики розроблених модульних функцій
    fillMatrix(A, N, a);
    printMatrix(A, N);
    findMinColumnSum(A, N);

    return 0;
}

