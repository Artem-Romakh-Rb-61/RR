/**
 * @file task1.c
 * @brief Розрахунок суми ряду без використання стандартних математичних функцій.
 * @details Варіант 14: S = sum_{n=0}^{N} (a^(2n) / (2n)!)[cite: 4]
 * @author Студент КПІ
 */

#include <stdio.h>
#include <stdlib.h>

int main() {
    // Встановлення кодування UTF-8 для коректного відображення української мови в консолі
    system("chcp 65001 > nul");

    double a;
    int N;

    // Введення дійсного числа 'a'
    printf("Введіть дійсне число a: ");
    scanf("%lf", &a);

    // Цикл перевірки коректності введеного значення N (згідно з умовою N >= 0)[cite: 4]
    do {
        printf("Введіть ціле число N (N >= 0): ");
        scanf("%d", &N);
        if (N < 0) {
            printf("Помилка! Значення N повинно бути більшим або рівним 0. Спробуйте ще раз.\n");
        }
    } while (N < 0);

    double sum = 1.0;  // Ініціалізація суми ряду (для n = 0 член ряду дорівнює 1)
    double term = 1.0; // Поточний член ряду (t_0 = 1 для n = 0)

    // Обчислення суми ряду за допомогою рекурентного співвідношення
    // Це дозволяє уникнути переповнення розрядної сітки при обчисленні великих факторіалів
    for (int n = 1; n <= N; ++n) {
        // Рекурентний перехід від t_{n-1} до t_n без використання бібліотеки math.h
        term = term * (a * a) / ((2.0 * n - 1) * (2.0 * n));
        sum += term;
    }

    // Виведення результату обчислень
    printf("Результат розрахунку суми ряду S = %.6f\n", sum);

    return 0;
}
